CREATE TABLE IF NOT EXISTS team_identity (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 person_key VARCHAR(40) NOT NULL UNIQUE,
 code VARCHAR(40) NOT NULL UNIQUE,
 origin VARCHAR(30) NOT NULL DEFAULT 'digital',
 route VARCHAR(160) NOT NULL DEFAULT '',
 position_name VARCHAR(120) NOT NULL DEFAULT '',
 consent_note VARCHAR(255) NOT NULL DEFAULT '',
 delivery_consent TINYINT NOT NULL DEFAULT 0,
 payout_verified TINYINT NOT NULL DEFAULT 0,
 template_json MEDIUMTEXT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS team_code_history (
 code VARCHAR(40) PRIMARY KEY,
 identity_id BIGINT UNSIGNED NOT NULL,
 changed_by BIGINT UNSIGNED NOT NULL,
 reason VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 KEY ix_person(identity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS team_sequences (
 prefix CHAR(1) PRIMARY KEY, next_number BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS team_card_jobs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ref VARCHAR(30) NOT NULL,
 recipient VARCHAR(20) NOT NULL,
 version_hash CHAR(64) NOT NULL,
 dedupe CHAR(64) NOT NULL UNIQUE,
 file_key CHAR(48) NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'queued',
 provider_ref VARCHAR(160) NULL,
 error VARCHAR(255) NULL,
 parent_id BIGINT UNSIGNED NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY ix_state(state,id), KEY ix_ref(ref,id), KEY ix_wamid(provider_ref)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS team_card_events (
 provider_ref VARCHAR(160) PRIMARY KEY,
 state VARCHAR(20) NOT NULL,
 error VARCHAR(255) NOT NULL DEFAULT '',
 event_at BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS team_reviews (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 person_key VARCHAR(40) NOT NULL,
 file_key CHAR(48) NOT NULL,
 mime VARCHAR(80) NOT NULL,
 suggestions MEDIUMTEXT NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 reviewed_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 KEY ix_person(person_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS team_terms (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 admin_id BIGINT UNSIGNED NOT NULL,
 basis VARCHAR(20) NOT NULL,
 rate DECIMAL(12,2) NOT NULL,
 salary DECIMAL(12,2) NOT NULL DEFAULT 0,
 effective_at DATETIME NOT NULL,
 reason VARCHAR(255) NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 KEY ix_effective(admin_id,effective_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS team_withdrawal_approvals (
 request_id BIGINT UNSIGNED PRIMARY KEY,
 approved_by BIGINT UNSIGNED NOT NULL,
 approved_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 payment_reference VARCHAR(120) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS team_notices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(160) NOT NULL,
 body TEXT NOT NULL,
 target VARCHAR(30) NOT NULL DEFAULT 'all',
 priority VARCHAR(20) NOT NULL DEFAULT 'normal',
 created_by BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS team_drafts (
 person_key VARCHAR(40) NOT NULL,
 admin_id BIGINT UNSIGNED NOT NULL,
 fields MEDIUMTEXT NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(person_key,admin_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS team_ledger_journal (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ledger_id BIGINT UNSIGNED NOT NULL,
 event_type VARCHAR(10) NOT NULL,
 old_row JSON NULL,
 new_row JSON NULL,
 recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 KEY ix_ledger(ledger_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
