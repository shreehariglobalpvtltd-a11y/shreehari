    private static function font(): string
    {
        return dirname(__DIR__) . '/assets/fonts/NotoSansDevanagari.ttf';
    }

    /** Draw text with y = TOP edge; faux-bold by a 1px double strike. */
    private static function text($im, float $size, int $x, int $y, int $col, string $text, bool $bold = false): void
    {
        if ($text === '') {
            return;
        }
        // The drawing boundary — see dev_shape() in helpers.php. Passenger
        // names reach this file in Devanagari since 11 Sep 2026, and GD does
        // not move the short-i matra in front of its consonant on its own.
        $text = dev_shape($text);
        $box = imagettfbbox($size, 0, self::font(), $text);
        $baseline = $y - (int) min($box[5], $box[7]);
        imagettftext($im, $size, 0, $x, $baseline, $col, self::font(), $text);
        if ($bold) {
            imagettftext($im, $size, 0, $x + 1, $baseline, $col, self::font(), $text);
        }
    }

    private static function width(float $size, string $text): int
    {
        if ($text === '') {
            return 0;
        }
        $box = imagettfbbox($size, 0, self::font(), dev_shape($text));
        return (int) (max($box[2], $box[4]) - min($box[0], $box[6]));
    }

    /** Cut a line to the width available, ending in ".." when it had to shrink. */
    private static function fit(float $size, string $text, int $maxW): string
    {
        if (self::width($size, $text) <= $maxW) {
            return $text;
        }
        /* mb_substr, not substr: a byte-wise cut lands inside a three-byte
           Devanagari codepoint and GD then draws NOTHING at all — the whole
           cell comes out blank rather than shortened. */
        $t = $text;
        while (mb_strlen($t) > 1 && self::width($size, $t . '..') > $maxW) {
            $t = mb_substr($t, 0, mb_strlen($t) - 1);
        }
        return rtrim($t) . '..';
    }

    private static function roundRect($im, int $x1, int $y1, int $x2, int $y2, int $r, int $fillCol, ?int $border): void
    {
        imagefilledrectangle($im, $x1 + $r, $y1, $x2 - $r, $y2, $fillCol);
        imagefilledrectangle($im, $x1, $y1 + $r, $x2, $y2 - $r, $fillCol);
        foreach ([[$x1 + $r, $y1 + $r], [$x2 - $r, $y1 + $r], [$x1 + $r, $y2 - $r], [$x2 - $r, $y2 - $r]] as [$cx, $cy]) {
            imagefilledellipse($im, $cx, $cy, $r * 2, $r * 2, $fillCol);
        }
        if ($border !== null) {
            imagerectangle($im, $x1, $y1, $x2, $y2, $border);
        }
    }

    private static function rupees(float $v): string
    {
        return 'Rs ' . number_format($v, 0);
    }

    public static function challanNo(array $sched): string
    {
        return 'CH-' . str_replace('-', '', (string) ($sched['travel_date'] ?? '')) . '-' . strtoupper((string) ($sched['route_code'] ?? ''))
             . ((int) ($sched['slot'] ?? 1) > 1 ? '-' . (int) $sched['slot'] : '');
    }

    /**
     * ASCII-only text for GD (no shaping engine): common Unicode
     * punctuation becomes its ASCII lookalike, everything else
     * (Devanagari, emoji) is dropped and an emptied "()" collapsed.
     *
     * This used to be a second, identical copy of Ticket::latin(). It is
     * now the one rule, borrowed — every PNG document in the app strips
     * text the same way, so a name cannot read one way on the ticket and
     * another on the challan (10 Sep 2026). ChallanPng::draw() already
     * calls Ticket::logoFile(), so ticket.php is loaded wherever this runs.
     */
    public static function roman(string $text): string
    {
        return Ticket::roman($text);
    }
