<?php
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { http_response_code(403); exit; }
define('SHG_APP', true);
require_once __DIR__ . '/../includes/agreementpdf.php';
$sample = ['agent_name' => 'श्री कृष्ण शर्मा', 'agreement_no' => 'SHG-2026-001', 'address' => 'नेपालगंज, नेपाल',
    'date' => '2026-09-27', 'currency' => 'INR', 'commission_type' => 'fixed', 'commission_rate' => '50',
    'payment_cycle' => 'हर महीने की 5 तारीख', 'fares' => [['route' => 'अहमदाबाद से नेपालगंज - सीट', 'amount' => '2000'],
    ['route' => 'अहमदाबाद से नेपालगंज - स्लीपर', 'amount' => '2500']]];
$checks = 0;
function check(bool $ok, string $label): void { global $checks; if (!$ok) { throw new RuntimeException($label); } $checks++; echo "PASS $label\n"; }
foreach (['date' => '2026-02-30', 'agent_name' => '<script>', 'currency' => 'USD', 'fares' => [], 'commission_rate' => '-1', 'address' => ['bad']] as $key => $value) {
    try { AgreementPdf::validate(array_replace($sample, [$key => $value])); throw new RuntimeException('Accepted bad ' . $key); }
    catch (InvalidArgumentException $e) { check(true, 'reject ' . $key); }
}
try { AgreementPdf::validate(array_replace($sample, ['commission_type' => 'percent', 'commission_rate' => '101'])); throw new RuntimeException('Accepted 101%'); }
catch (InvalidArgumentException $e) { check(true, 'reject commission above 100%'); }
if (getenv('SHG_DEVSHAPE_OFF')) {
    try { AgreementPdf::generate($sample); throw new LogicException('Issued unshaped Hindi'); }
    catch (RuntimeException $e) { check(str_contains($e->getMessage(), 'shaping'), 'missing shaping fails closed'); }
    exit;
}
$shape = DevShape::shape('श्री कृष्ण क्षत्रिय अनुबंध वित्तीय');
check($shape !== null && !in_array(0, array_column($shape['g'], 0), true), 'Hindi conjuncts contain no missing glyphs');
$pdf = AgreementPdf::generate($sample);
check(str_starts_with($pdf, '%PDF-1.4'), 'PDF generated by existing writer');
check(str_contains($pdf, '/FontFile2'), 'TrueType font embedded');
check(preg_match_all('~/Type /Page\b~', $pdf) === 2, 'sample has two pages');
$large = $sample;
$large['agent_name'] = str_repeat('कृष्ण शर्मा ', 6);
$large['address'] = str_repeat('काठमांडू नेपालगंज ', 9);
$large['payment_cycle'] = str_repeat('हर महीने भुगतान ', 5);
$large['fares'] = array_fill(0, 6, ['route' => str_repeat('नेपालगंज अहमदाबाद ', 4), 'amount' => '9999999.99']);
$large['commission_type'] = 'percent'; $large['commission_rate'] = '12.5';
$more = AgreementPdf::generate($large);
check(preg_match_all('~/Type /Page\b~', $more) >= 3, 'long inputs paginate');
if (isset($argv[1])) { file_put_contents($argv[1], $pdf); file_put_contents(dirname($argv[1]) . '/agreement-long.pdf', $more); }
echo "$checks checks passed. No database or configuration loaded.\n";
